/**
 * ============================================================================
 * BLOCKQUOTE & GITHUB ALERTS RENDERER (components/markdown/renderers/blockquote.js)
 * ============================================================================
 *
 * Supports:
 * > Normal quote
 *
 * > [!NOTE]
 * > Information
 *
 * > [!TIP]
 * > Helpful advice
 *
 * > [!IMPORTANT]
 * > Important information
 *
 * > [!WARNING]
 * > Warning
 *
 * > [!CAUTION]
 * > Dangerous action
 *
 * Detection is performed against the Markdown token/source rather than
 * generated HTML so it remains reliable with `breaks: true`.
 * ============================================================================
 */

(function (global) {
    const TYPES = {
        NOTE: "note",
        TIP: "tip",
        IMPORTANT: "important",
        WARNING: "warning",
        CAUTION: "caution"
    };

    const ICONS = {
        note: "ⓘ",
        tip: "✦",
        important: "!",
        warning: "⚠",
        caution: "!"
    };

    const LABELS = {
        note: "Note",
        tip: "Tip",
        important: "Important",
        warning: "Warning",
        caution: "Caution"
    };

    function getAlertType(token) {
        /*
         * Prefer the original Markdown source.
         * Marked blockquote tokens expose `text` and `raw`.
         * This avoids depending on the exact HTML generated by the parser.
         */
        const candidates = [
            token?.text,
            token?.raw
        ];

        for (const source of candidates) {
            if (!source) continue;
            const normalized = String(source)
                .replace(/\r\n?/g, "\n")
                .replace(/^>\s?/gm, "")
                .trim();

            const match = normalized.match(
                /^\[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\](?:\s*\n|$)/i
            );
            if (match) {
                return TYPES[match[1].toUpperCase()];
            }
        }

        /*
         * Final compatibility fallback.
         * Some Marked versions/configurations may expose slightly different token structures.
         */
        if (Array.isArray(token?.tokens) && token.tokens.length > 0) {
            const firstToken = token.tokens[0];
            const firstText = String(
                firstToken?.text || firstToken?.raw || ""
            )
                .replace(/\r\n?/g, "\n")
                .trim();

            const match = firstText.match(
                /^\[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\]/i
            );
            if (match) {
                return TYPES[match[1].toUpperCase()];
            }
        }

        return null;
    }

    function renderAlertBody(token, parser) {
        /*
         * Render the original child tokens first.
         */
        let html = token.tokens && parser ? parser.parse(token.tokens) : String(token.text || "");

        /*
         * Remove the alert marker regardless of whether Marked generated:
         * <p>[!NOTE]</p>
         * or:
         * <p>[!NOTE]<br>...</p>
         * or another equivalent representation.
         */
        html = html.replace(
            /^\s*<p>\s*\[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\]\s*(?:<br\s*\/?>\s*)?/i,
            ""
        );

        /*
         * If the marker was its own paragraph, remove the complete paragraph.
         */
        html = html.replace(
            /^\s*<p>\s*\[!(NOTE|TIP|IMPORTANT|WARNING|CAUTION)\]\s*<\/p>\s*/i,
            ""
        );

        return html;
    }

    global.MarkdownBlockquoteRenderer = {
        render(token, parser) {
            const type = getAlertType(token);

            /*
             * Normal blockquote.
             */
            if (!type) {
                const html = token.tokens && parser ? parser.parse(token.tokens) : String(token.text || "");
                return `<blockquote>${html}</blockquote>`;
            }

            const icon = ICONS[type];
            const label = LABELS[type];
            const body = renderAlertBody(token, parser);

            return `
<aside class="ai-callout ai-callout--${type}" role="note" data-callout="${type}" aria-label="${label}">
    <div class="ai-callout-title">
        <span class="ai-callout-icon" aria-hidden="true">${icon}</span>
        <span class="ai-callout-label">${label}</span>
    </div>
    <div class="ai-callout-body">
        ${body}
    </div>
</aside>`.trim();
        }
    };
})(window);
